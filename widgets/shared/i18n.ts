// (`i18n/*.yml` files pulled in with `!extend`, keyed by language code). Seelen offers third-party widgets no translation
// API for their panels, so those texts live here: the Traditional Chinese text is the key and a missing entry falls
// back to it. The language is the one chosen in Seelen's settings (the system language when unset), not a switch of our own.
import { Settings } from "@seelen-ui/lib";
export type Lang = "zh" | "ja" | "en";
const pick = (code: string): Lang => { const c = code.toLowerCase(); return c.startsWith("zh") ? "zh" : c.startsWith("ja") ? "ja" : "en"; };
const settings = await Settings.getAsync().catch(() => null);
export const lang: Lang = pick(settings?.inner.language || navigator.language || "zh-TW");
// a panel keeps its texts for as long as it lives, so follow a language change by reloading it
Settings.onChange((s) => { if (pick(s.inner.language || navigator.language || "zh-TW") !== lang) location.reload(); }).catch(() => {});
// Han unification: the page language picks the glyph forms (a Japanese page must not get Traditional Chinese kanji)
document.documentElement.lang = lang === "zh" ? "zh-TW" : lang === "ja" ? "ja" : "en";
export const locale = lang === "zh" ? "zh-TW" : lang === "ja" ? "ja-JP" : "en-US";

